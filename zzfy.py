def split(s: str, dct: dict, vt: tuple[str, ...], ct: tuple[str, ...], o: tuple[str,...] = ()) ->tuple[str, ...]:
    s = "".join(c for c in s).lower().replace(" ", "").replace("'", "")
    if "s" in o:
        print(s)
    r = []
    u = [False] * (len(s) + 1)
    for i in range(len(s)):
        if u[i]:
            continue
        if not s[i].isalpha():
            r.append(s[i])
            continue
        f = True
        for j in range(i,len(s)):
            u[j] = True
            if dct.get(s[i:j+1]):
                r.append(s[i:j+1])
                f = False
                break
        if f:
            r.append(s[i])
            for j in range(i, len(s)):
                u[j] = False
    f = False
    for i in range(len(r)-2):
        if f:
            f = False
            continue
        try:
            if (len(r[i]) == 1) and (r[i] not in OO) and (len(r[i+1]) == 1) and (r[i+1] not in OO) and (r[i] in ct) and (r[i+1] in vt):
                r[i] += r[i+1]
                del r[i+1]
                f = True
        except IndexError:
            continue
    if "r" in o:
        print(r)
    return tuple(r)


